def main():
    conn = pymysql.connect(**DB_CONFIG, cursorclass=pymysql.cursors.DictCursor)
    try:
        with conn.cursor() as cursor:
            total = 0
            for subject, topics in CURRICULUM.items():
                for step_order, (grade, unit_name, description) in enumerate(topics, start=1):
                    cursor.execute(
                        '''INSERT INTO curriculum_topics (subject, grade, step_order, unit_name, description)
                           VALUES (%s, %s, %s, %s, %s)
                           ON DUPLICATE KEY UPDATE
                             grade = VALUES(grade), unit_name = VALUES(unit_name), description = VALUES(description)''',
                        (subject, grade, step_order, unit_name, description)
                    )
                    total += 1
            conn.commit()
            print(f'시드 완료: {total}개 단원')

            cursor.execute('SELECT subject, COUNT(*) AS cnt FROM curriculum_topics GROUP BY subject')
            for row in cursor.fetchall():
                print(' ', row)
    finally:
        conn.close()


if __name__ == '__main__':
    main()
